@app.post("/api/conversations/{conversation_id}/regenerate")
def regenerate_response(conversation_id: int):

    if not client:
        raise HTTPException(
            status_code=500,
            detail="Gemini API key is missing. Check backend/.env"
        )

    with get_connection() as connection:

        # Retrieve all messages in this conversation.
        messages = connection.execute("""
            SELECT id, role, content
            FROM messages
            WHERE conversation_id = ?
            ORDER BY id ASC
        """, (conversation_id,)).fetchall()

        if not messages:
            raise HTTPException(
                status_code=404,
                detail="Conversation not found or has no messages."
            )

        # The most recent message must be an AI response.
        last_message = messages[-1]

        if last_message["role"] != "assistant":
            raise HTTPException(
                status_code=400,
                detail="There is no AI response to regenerate."
            )

        # Remove the previous AI response from the context.
        previous_messages = messages[:-1]

        if not previous_messages or previous_messages[-1]["role"] != "user":
            raise HTTPException(
                status_code=400,
                detail="Could not find the previous user message."
            )

    # Prepare the previous conversation for Gemini.
    contents = []

    for item in previous_messages[-20:]:

        if item["role"] not in ["user", "assistant"]:
            continue

        role = "model" if item["role"] == "assistant" else "user"

        contents.append({
            "role": role,
            "parts": [{"text": item["content"]}]
        })

    try:

        response = client.models.generate_content(
            model=MODEL,
            contents=contents,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION,
                temperature=0.9,
                max_output_tokens=2048
            )
        )

        if not response.text:
            raise HTTPException(
                status_code=502,
                detail="Gemini returned an empty response."
            )

        new_reply = response.text
        timestamp = current_time()

        # Replace the previous AI response.
        with get_connection() as connection:

            connection.execute("""
                UPDATE messages
                SET content = ?, created_at = ?
                WHERE id = ?
                AND conversation_id = ?
                AND role = 'assistant'
            """, (
                new_reply,
                timestamp,
                last_message["id"],
                conversation_id
            ))

            connection.execute("""
                UPDATE conversations
                SET updated_at = ?
                WHERE id = ?
            """, (timestamp, conversation_id))

        return {
            "reply": new_reply,
            "conversation_id": conversation_id,
            "provider": "Google Gemini",
            "model": MODEL
        }

    except HTTPException:
        raise

    except Exception:

        logger.exception("Gemini regeneration failed")

        raise HTTPException(
            status_code=502,
            detail=(
                "VORTEX AI could not regenerate the response. "
                "Check your API key, internet connection and model access."
            )
        )

@app.websocket("/ws/voice")
async def voice_websocket(websocket: WebSocket):

    await websocket.accept()

    if not client:
        await websocket.send_json({
            "type": "error",
            "message": "Gemini API is not configured."
        })
        await websocket.close()
        return

    config = types.LiveConnectConfig(
        response_modalities=["AUDIO"],
        system_instruction=VOICE_SYSTEM_INSTRUCTION,
        speech_config=types.SpeechConfig(
            voice_config=types.VoiceConfig(
                prebuilt_voice_config=types.PrebuiltVoiceConfig(
                    voice_name="Aoede"
                )
            )
        ),
        input_audio_transcription=types.AudioTranscriptionConfig(),
        output_audio_transcription=types.AudioTranscriptionConfig(),
        http_options=types.HttpOptions(
            api_version="v1beta"
        )
    )

    try:

        async with client.aio.live.connect(
            model=VOICE_MODEL,
            config=config
        ) as session:

            await websocket.send_json({
                "type": "connected",
                "message": "VORTEX Voice Mode connected."
            })

            async def receive_from_browser():

                while True:

                    message = await websocket.receive()

                    if message.get("bytes"):

                        await session.send_realtime_input(
                            audio=types.Blob(
                                data=message["bytes"],
                                mime_type="audio/pcm;rate=16000"
                            )
                        )

                    elif message.get("text"):

                        import json

                        data = json.loads(message["text"])

                        if data.get("type") == "text":
                            await session.send_realtime_input(
                                text=data.get("text", "")
                            )

            async def receive_from_gemini():

                while True:

                    async for response in session.receive():

                        if not response.server_content:
                            continue

                        content = response.server_content

                        if content.interrupted:
                            await websocket.send_json({
                                "type": "interrupted"
                            })

                        if content.input_transcription:
                            await websocket.send_json({
                                "type": "input_transcription",
                                "text": content.input_transcription.text
                            })

                        if content.output_transcription:
                            await websocket.send_json({
                                "type": "output_transcription",
                                "text": content.output_transcription.text
                            })

                        if content.model_turn:

                            for part in content.model_turn.parts:

                                if part.inline_data and part.inline_data.data:

                                    await websocket.send_bytes(
                                        part.inline_data.data
                                    )

                        if content.turn_complete:

                            await websocket.send_json({
                                "type": "turn_complete"
                            })

            browser_task = asyncio.create_task(
                receive_from_browser()
            )

            gemini_task = asyncio.create_task(
                receive_from_gemini()
            )

            done, pending = await asyncio.wait(
                [browser_task, gemini_task],
                return_when=asyncio.FIRST_COMPLETED
            )

            for task in pending:
                task.cancel()

            await asyncio.gather(
                *pending,
                return_exceptions=True
            )

    except WebSocketDisconnect:
        logger.info("VORTEX Voice Mode disconnected.")

    except Exception:
        logger.exception("VORTEX Voice Mode error.")

        try:
            await websocket.send_json({
                "type": "error",
                "message": "Voice connection failed."
            })
        except Exception:
            pass